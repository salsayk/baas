INSERT INTO languages_screens_translations (source_text, language_id, translated_text)
SELECT s.source_text, lm.id,
       CASE WHEN lm.direction = 0 THEN s.en_text ELSE s.he_text END AS translated_text
FROM (
  SELECT source_text, MAX(en_text) AS en_text, MAX(he_text) AS he_text
  FROM seed
  GROUP BY source_text
) s
CROSS JOIN lang_map lm
ON CONFLICT (language_id, source_text) DO UPDATE
SET translated_text = EXCLUDED.translated_text;
