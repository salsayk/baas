  source_text     TEXT NOT NULL,
  language_id     BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  translated_text TEXT NOT NULL,
  UNIQUE (language_id, source_text)
);

CREATE INDEX IF NOT EXISTS idx_languages_screens_translations_language_id ON languages_screens_translations(language_id);
CREATE INDEX IF NOT EXISTS idx_languages_screens_translations_source_text ON languages_screens_translations(source_text);

COMMENT ON TABLE languages_screens_translations IS 'UI label translations by language.';
COMMENT ON COLUMN languages_screens_translations.source_text IS 'Source label text (English canonical phrase).';
